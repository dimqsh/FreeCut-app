/// Relative luminance (WCAG 2), in 10⁻¹⁰ units: 0 for black,
/// 10,000,000,000 for white. Alpha is ignored.
pub(crate) fn luminance(c: Rgba8) -> u64 {
    let lin = |v: u8| u64::from(LINEAR[usize::from(v)]);
    2126 * lin(c.r) + 7152 * lin(c.g) + 722 * lin(c.b)
}

/// Whether `a` and `b` contrast at least `ratio_tenths / 10` : 1 (WCAG
/// 2's `(L1 + 0.05) / (L2 + 0.05)`).
pub(crate) fn contrasts(a: Rgba8, b: Rgba8, ratio_tenths: u64) -> bool {
    // 0.05 in the 10⁻¹⁰ units of `luminance`.
    const OFFSET: u64 = 500_000_000;
    let (la, lb) = (luminance(a), luminance(b));
    let (hi, lo) = (la.max(lb), la.min(lb));
    (hi + OFFSET) * 10 >= (lo + OFFSET) * ratio_tenths
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn luminance_and_contrast_follow_wcag() {
        assert_eq!(luminance(Rgba8::BLACK), 0);
        assert_eq!(luminance(Rgba8::WHITE), 10_000_000_000);
        // Black on white is 21:1.
        assert!(contrasts(Rgba8::BLACK, Rgba8::WHITE, 210));
        assert!(!contrasts(Rgba8::BLACK, Rgba8::WHITE, 211));
        assert!(!contrasts(Rgba8::WHITE, Rgba8::WHITE, 30));
        // #767676 on white is about 4.54:1.
        let grey = Rgba8::new(0x76, 0x76, 0x76, 255);
        assert!(contrasts(grey, Rgba8::WHITE, 45));
        assert!(!contrasts(grey, Rgba8::WHITE, 46));
        assert!(contrasts(Rgba8::WHITE, Rgba8::DARK, 30));
    }
}
