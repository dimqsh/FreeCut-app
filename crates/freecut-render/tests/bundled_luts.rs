//! FreeCut's bundled LUTs (CL-045): eight 33³ `.cube` files under
//! `assets/luts/`, generated from FreeCut-written recipes
//! (`assets/luts/recipes/*.json`) by FreeCut's own colour stack, plus
//! `assets/luts/manifest.json`. Everything there is CC0-1.0.
//!
//! `bundled_luts_rebake_byte_identically` regenerates every file in memory
//! and compares the bytes with the checked-in ones; the ignored
//! `regenerate_bundled_luts` writes them on purpose:
//!
//! ```text
//! cargo test -p freecut-render --test bundled_luts -- --ignored regenerate
//! ```
//!
//! A recipe is `{ id, name, tags, rev, summary, file, passes }`; each pass
//! is a colour stack given by slider values (`params`, named as in project
//! files: `temperature`, `wheels.shadows.luma`, …), curves (`curves`:
//! channel → `[[x, y], …]` in 0–10000) and wheel pucks (`pucks`: wheel →
//! `[x, y]`). Passes run one after another, so a look can tint after
//! desaturating.
#![allow(clippy::unwrap_used, clippy::expect_used)] // test code

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use freecut_media::lut::parse_cube;
use freecut_render::color::eval_pixel;
use freecut_timeline::model::{
    ColorParamId, ColorStack, Curve, CurveChannel, CurvePoint, WheelId, hash_hex,
};
use serde_json::Value;

const SIZE: usize = 33;

fn assets() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../assets/luts")
}

/// One recipe, read from its JSON.
struct Recipe {
    id: String,
    name: String,
    tags: Vec<String>,
    rev: u64,
    summary: String,
    file: String,
    passes: Vec<ColorStack>,
}

fn pass(v: &Value) -> ColorStack {
    let mut s = ColorStack::default();
    if let Some(params) = v["params"].as_object() {
        for (name, value) in params {
            let id = ColorParamId::parse(name).unwrap_or_else(|| panic!("unknown slider {name}"));
            s = s.with(id, i16::try_from(value.as_i64().unwrap()).unwrap());
        }
    }
    if let Some(curves) = v["curves"].as_object() {
        for (name, points) in curves {
            let channel = CurveChannel::parse(name).unwrap();
            let points = points
                .as_array()
                .unwrap()
                .iter()
                .map(|p| {
                    let xy = |i: usize| u16::try_from(p[i].as_u64().unwrap()).unwrap();
                    CurvePoint::new(xy(0), xy(1))
                })
                .collect();
            s = s.with_curve(channel, Curve::new(points).unwrap());
        }
    }
    if let Some(pucks) = v["pucks"].as_object() {
        for (name, xy) in pucks {
            let wheel = WheelId::parse(name).unwrap();
            let c = |i: usize| i16::try_from(xy[i].as_i64().unwrap()).unwrap();
            s = s.with_puck(wheel, c(0), c(1));
        }
    }
    s
}

fn recipes() -> Vec<(String, Recipe)> {
    let dir = assets().join("recipes");
    let mut paths: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "json"))
        .collect();
    paths.sort();
    paths
        .into_iter()
        .map(|path| {
            let v: Value = serde_json::from_slice(&std::fs::read(&path).unwrap()).unwrap();
            let text = |k: &str| v[k].as_str().unwrap().to_owned();
            let stem = path.file_stem().unwrap().to_str().unwrap().to_owned();
            let recipe = Recipe {
                id: text("id"),
                name: text("name"),
                tags: v["tags"]
                    .as_array()
                    .unwrap()
                    .iter()
                    .map(|t| t.as_str().unwrap().to_owned())
                    .collect(),
                rev: v["rev"].as_u64().unwrap(),
                summary: text("summary"),
                file: text("file"),
                passes: v["passes"].as_array().unwrap().iter().map(pass).collect(),
            };
            assert_eq!(recipe.file, format!("{stem}.cube"), "{}", path.display());
            (stem, recipe)
        })
        .collect()
}

/// One output channel as written: clamped to 0–1 (`+ 0.0` turns −0 into
/// 0) with six decimals.
fn channel(v: f32) -> f32 {
    v.clamp(0.0, 1.0) + 0.0
}

/// The `.cube` text of a recipe: a commented header, the title, the size,
/// the domain and 33³ lines, red fastest.
fn bake(stem: &str, r: &Recipe) -> String {
    let mut out = String::new();
    writeln!(
        out,
        "# FreeCut bundled LUT: {} ({}, rev {})",
        r.name, r.id, r.rev
    )
    .unwrap();
    writeln!(
        out,
        "# Generated by FreeCut's colour stack from recipes/{stem}.json."
    )
    .unwrap();
    writeln!(out, "# License: CC0-1.0 (public domain dedication).").unwrap();
    writeln!(out, "TITLE \"{}\"", r.name).unwrap();
    writeln!(out, "LUT_3D_SIZE {SIZE}").unwrap();
    writeln!(out, "DOMAIN_MIN 0.0 0.0 0.0").unwrap();
    writeln!(out, "DOMAIN_MAX 1.0 1.0 1.0").unwrap();
    let last = (SIZE - 1) as f32;
    for b in 0..SIZE {
        for g in 0..SIZE {
            for rr in 0..SIZE {
                let input = [rr as f32 / last, g as f32 / last, b as f32 / last];
                let v = r.passes.iter().fold(input, |c, s| eval_pixel(s, c));
                writeln!(
                    out,
                    "{:.6} {:.6} {:.6}",
                    channel(v[0]),
                    channel(v[1]),
                    channel(v[2])
                )
                .unwrap();
            }
        }
    }
    out
}

fn json_str(s: &str) -> String {
    Value::String(s.to_owned()).to_string()
}

/// `manifest.json`: id, display name, tags, rev, summary, file name and the
/// XXH3-128 of the file's bytes, in file-name order.
fn manifest(entries: &[(String, Recipe, String)]) -> String {
    let mut out = String::from("{\n  \"license\": \"CC0-1.0\",\n  \"luts\": [\n");
    for (i, (_, r, cube)) in entries.iter().enumerate() {
        let hash = hash_hex(&xxhash_rust::xxh3::xxh3_128(cube.as_bytes()).to_be_bytes());
        let tags: Vec<String> = r.tags.iter().map(|t| json_str(t)).collect();
        write!(
            out,
            "    {{\n      \"id\": {},\n      \"name\": {},\n      \"tags\": [{}],\n      \"rev\": {},\n      \"summary\": {},\n      \"file\": {},\n      \"hash\": \"{hash}\"\n    }}",
            json_str(&r.id),
            json_str(&r.name),
            tags.join(", "),
            r.rev,
            json_str(&r.summary),
            json_str(&r.file),
        )
        .unwrap();
        out.push_str(if i + 1 == entries.len() { "\n" } else { ",\n" });
    }
    out.push_str("  ]\n}\n");
    out
}

fn generated() -> (Vec<(String, Recipe, String)>, String) {
    let entries: Vec<(String, Recipe, String)> = recipes()
        .into_iter()
        .map(|(stem, r)| {
            let cube = bake(&stem, &r);
            (stem, r, cube)
        })
        .collect();
    let manifest = manifest(&entries);
    (entries, manifest)
}

fn read(path: &Path) -> String {
    String::from_utf8(
        std::fs::read(path)
            .unwrap_or_else(|e| panic!("{}: {e}; run the ignored regenerate test", path.display())),
    )
    .unwrap()
}

#[test]
fn bundled_luts_rebake_byte_identically() {
    let (entries, manifest) = generated();
    assert_eq!(entries.len(), 8, "CL-045 ships eight LUTs");
    for (_, r, cube) in &entries {
        let on_disk = read(&assets().join(&r.file));
        assert!(
            on_disk == *cube,
            "{} differs from its recipe's bake",
            r.file
        );
    }
    assert!(
        read(&assets().join("manifest.json")) == manifest,
        "manifest.json differs"
    );
}

#[test]
fn bundled_luts_parse_and_keep_black_and_white_neutral() {
    let (entries, _) = generated();
    let mut ids = std::collections::BTreeSet::new();
    for (_, r, cube) in &entries {
        assert!(ids.insert(r.id.clone()), "duplicate id {}", r.id);
        let lut = parse_cube(cube.as_bytes()).unwrap();
        assert_eq!(lut.title.as_deref(), Some(r.name.as_str()));
        let table = lut.cube.as_ref().unwrap();
        assert_eq!(table.size(), SIZE as u32);
        assert!(lut.skipped_keywords == 0 && lut.notices.is_empty());
        assert!(!lut.is_identity(), "{} changes the picture", r.name);
        // CL-045: pure black and white stay within ±0.08 of a neutral
        // grey, so a look never paints borders.
        for corner in [table.at(0, 0, 0), table.at(SIZE - 1, SIZE - 1, SIZE - 1)] {
            let grey = (corner[0] + corner[1] + corner[2]) / 3.0;
            for c in corner {
                assert!((c - grey).abs() <= 0.08, "{}: {corner:?}", r.name);
            }
        }
    }
}

#[test]
#[ignore = "writes assets/luts; run on purpose after changing a recipe"]
fn regenerate_bundled_luts() {
    let (entries, manifest) = generated();
    for (_, r, cube) in &entries {
        std::fs::write(assets().join(&r.file), cube).unwrap();
    }
    std::fs::write(assets().join("manifest.json"), manifest).unwrap();
}
